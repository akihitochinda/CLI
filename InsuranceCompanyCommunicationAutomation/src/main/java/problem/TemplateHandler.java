package problem;

import java.io.BufferedReader;
import java.io.FileNotFoundException;
import java.io.FileReader;
import java.io.IOException;
import java.util.Map;
import java.util.Objects;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Class for TemplateHandler that takes a templates and replace the placeholder header name
 * with CSV file's corresponding person name/email address
 */
public class TemplateHandler {
  private String template;

  /**
   * Constructor for TemplateHandler
   * @param path the letter/email path for the template used for producing automatic letter/email
   * @throws InvalidArgumentsException throw Exception when FileNotFound or cannot open
   */
  public TemplateHandler(String path) throws InvalidArgumentsException {
    this.template = this.readTemplate(path);
  }

  /**
   * Method to add the lines together per reading the file and return everything as a String
   * @param path the file path
   * @return the csv file contents to a string
   * @throws InvalidArgumentsException throw Exception when FileNotFound or cannot open
   */
  public String readTemplate(String path) throws InvalidArgumentsException {
    StringBuilder lines = new StringBuilder();
    try (BufferedReader reader= new BufferedReader(new FileReader(path))) {
      String line = "";
      while ((line = reader.readLine()) != null) {
        lines.append(line); // it only appends line without the operator
        lines.append(System.lineSeparator()); }// add "/n" line breaks on all OS systems
      } catch(FileNotFoundException e){
        throw new InvalidArgumentsException(path + "not found");
      } catch(IOException e){
        throw new InvalidArgumentsException("IO Exception");
      }
      return lines.toString();
  }

  /**
   * Method to replace the placeholder/the word inside [[]]
   * @param replacements the replacements is the HashMap with header key and value which is the
   *                     person's info (etc. email address, first name, last name);
   * @return the letter/email generated by replacing the placeholder
   */
  public String replacePlaceholders(Map<String, String> replacements) {
    // work on a copy of the template
    String newTemplate = this.template;
    // Pattern defines what to search for, search for word inside [[ ]]
    Pattern reg = Pattern.compile("\\[\\[(\\w*)\\]\\]");
    Matcher matcher = reg.matcher(this.template);
    while (matcher.find()) {
      // find the word inside the placeholder
      String placeholder = matcher.group(1);
      // try to find the value associated with the header/placeholder
      String value = replacements.get(placeholder);
      // then try to replace the new value with the placeholder value
      if (value == null) value = ""; // avoid exception error "replacement" is null
      newTemplate = newTemplate.replace("[[" + placeholder + "]]", value);
    }
    return newTemplate;
  }

  /**
   * Getter for template
   * @return template
   */
  public String getTemplate() {
    return this.template;
  }

  @Override
  public String toString() {
    return "TemplateHandler{" +
        "template='" + template + '\'' +
        '}';
  }

  @Override
  public boolean equals(Object o) {
    if (o == null || getClass() != o.getClass()) {
      return false;
    }
    TemplateHandler that = (TemplateHandler) o;
    return Objects.equals(template, that.template);
  }

  @Override
  public int hashCode() {
    return Objects.hashCode(template);
  }
}
